// Levenshtein for Part 3 fuzzy matching
export function levenshtein(a: string, b: string): number {
  const m = a.length, n = b.length
  const dp: number[][] = Array.from({ length: m + 1 }, (_, i) => [i])
  for (let j = 0; j <= n; j++) dp[0][j] = j
  for (let i = 1; i <= m; i++) {
    for (let j = 1; j <= n; j++) {
      dp[i][j] = a[i - 1] === b[j - 1]
        ? dp[i - 1][j - 1]
        : 1 + Math.min(dp[i - 1][j], dp[i][j - 1], dp[i - 1][j - 1])
    }
  }
  return dp[m][n]
}

export function checkPart3Answer(userAnswer: string, correctAnswers: string[]): boolean {
  const normalized = userAnswer.toLowerCase().trim()
  return correctAnswers.some(correct => {
    const c = correct.toLowerCase().trim()
    if (normalized.includes(c) || c.includes(normalized)) return true
    const maxLen = Math.max(normalized.length, c.length)
    if (maxLen === 0) return true
    const dist = levenshtein(normalized, c)
    return dist / maxLen <= 0.3
  })
}
