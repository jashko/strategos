export function getLecture(id: number): Lecture | undefined {
  return LECTURES.find(l => l.id === id)
}

export function getConcept(conceptId: string): { concept: import('../types').Concept; lecture: Lecture } | undefined {
  for (const lecture of LECTURES) {
    const concept = lecture.concepts.find(c => c.id === conceptId)
    if (concept) return { concept, lecture }
  }
  return undefined
}

export function getAllConcepts(): Array<{ concept: import('../types').Concept; lecture: Lecture }> {
  return LECTURES.flatMap(lecture => lecture.concepts.map(concept => ({ concept, lecture })))
}
